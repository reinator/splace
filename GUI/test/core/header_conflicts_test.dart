import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:splace/src/core/genbank_markers.dart';
import 'package:splace/src/core/marker_search.dart';
import 'package:splace/src/state/project_controller.dart';
import 'package:splace/src/ui/methods_text.dart';

/// One partial CDS record (a barcode-like fragment) of [gene].
String _record(String accession, String organism, String gene, String product) => '''
LOCUS       ${accession.split('.').first}               30 bp    DNA     linear   VRT 01-JAN-2024
DEFINITION  $organism $product ($gene) gene, partial cds; mitochondrial.
ACCESSION   ${accession.split('.').first}
VERSION     $accession
SOURCE      mitochondrion $organism
  ORGANISM  $organism
            Eukaryota; Metazoa; Chordata; Craniata; Vertebrata; Actinopterygii;
            Carangiformes; Carangidae; Caranx.
FEATURES             Location/Qualifiers
     source          1..30
                     /organism="$organism"
                     /organelle="mitochondrion"
     CDS             <1..>30
                     /gene="$gene"
                     /codon_start=1
                     /transl_table=2
                     /product="$product"
ORIGIN
        1 atgacccacc tactaaaaat cattaacaac
//
''';

void main() {
  late Directory tmp;
  late ProjectController c;

  setUp(() async {
    tmp = Directory.systemTemp.createTempSync('splace_hdr_');
    final gb = File(p.join(tmp.path, 'markers.gb'))
      ..writeAsStringSync([
        _record('MK000001.1', 'Caranx hippos', 'COX1', 'cytochrome c oxidase subunit I'),
        _record('MK000002.1', 'Caranx hippos', 'COX1', 'cytochrome c oxidase subunit I'),
        _record('MK000003.1', 'Caranx hippos', 'CYTB', 'cytochrome b'),
        _record('MK000004.1', 'Caranx latus', 'COX1', 'cytochrome c oxidase subunit I'),
      ].join());
    c = ProjectController(autoDetectTools: false)..workDir = p.join(tmp.path, 'project');
    await c.addGenBankFiles([gb.path]);
    c.skipTaxonomy();
    c.toggleFeatureType('CDS', true);
  });

  tearDown(() {
    c.dispose();
    tmp.deleteSync(recursive: true);
  });

  test('a header repeated inside one marker blocks the alignment', () async {
    expect(c.records, hasLength(4));
    c.setHeader(const HeaderTemplate(fields: ['species']));
    // Two COI records of Caranx hippos; its CYTB record is another marker.
    expect(c.headerConflicts(), {'Caranx_hippos': ['MK000001.1', 'MK000002.1']});
    expect(c.headerBlocked, isTrue);
    c.confirmHeader();
    expect(c.headerConfirmed, isFalse, reason: 'cannot confirm repeated headers');
    await c.alignAll();
    expect(c.loci.values.where((l) => l.aligned != null), isEmpty, reason: 'alignment locked');

    // Only CYTB selected: the same header in different markers is fine.
    c.toggleMarker('CYTB', true);
    expect(c.headerConflicts(), isEmpty);
    c.toggleMarker('CYTB', false);

    // The accession tells the records apart.
    c.setHeader(const HeaderTemplate(fields: ['species', 'accession']));
    expect(c.headerBlocked, isFalse);
    c.confirmHeader();
    expect(c.headerConfirmed, isTrue);

    // One sample per species joins them on purpose: not a conflict.
    c.setOnePerTaxon(true);
    expect(c.headerConflicts(), isEmpty);
    expect(c.headerBlocked, isFalse);
  });

  test('records not named to species are not joined: every step after the names stays locked', () async {
    final gb = File(p.join(tmp.path, 'sp.gb'))
      ..writeAsStringSync([
        _record('MK000005.1', 'Caranx sp.', 'COX1', 'cytochrome c oxidase subunit I'),
        _record('MK000006.1', 'Caranx sp.', 'COX1', 'cytochrome c oxidase subunit I'),
      ].join());
    await c.addGenBankFiles([gb.path]);
    c.setOnePerTaxon(true);
    c.toggleMarker('COI', true);
    final dups = c.headerConflicts();
    expect(dups.values.single, ['MK000005.1', 'MK000006.1']);
    expect(c.headerBlocked, isTrue);
    await c.alignAll();
    await c.buildMatrix();
    await c.runSaturation();
    expect(c.loci.values.where((l) => l.aligned != null), isEmpty);
    expect(c.matrix, isNull);
    expect(c.logs.where((l) => l.message.contains('blocked')), isNotEmpty);
  });

  test('partial markers make the saturation test optional', () async {
    c.setOnePerTaxon(true);
    c.toggleMarker('COI', true);
    await c.prepareLoci();
    expect(c.loci['COI']!.partial, 2, reason: 'one sequence per species, both partial');
    expect(c.loci['COI']!.mostlyPartial, isTrue);
  });

  test('the methods text says SynGenes built the marker searches', () {
    c.markerSearches.add((search: const MarkerSearch(taxon: 'Caranx', genes: ['COI', 'CYTB']), records: 4));
    c.setOnePerTaxon(true);
    final en = buildMethodsText(c, 'en');
    expect(en.cited, contains('SynGenes'));
    final text = en.paragraphs.join(' ');
    expect(text, contains('COI and CYTB of Caranx'));
    expect(text, contains('Entrez queries generated by SynGenes'));
    expect(text, contains('marker_queries.txt'));
    expect(text, contains('longest sequence'));
    expect(buildMethodsText(c, 'pt').paragraphs.join(' '), contains('buscas Entrez geradas pelo SynGenes'));
  });
}
