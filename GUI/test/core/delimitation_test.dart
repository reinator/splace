import 'package:flutter_test/flutter_test.dart';
import 'package:splace/src/core/delimitation.dart';
import 'package:splace/src/core/newick.dart';

void main() {
  // Written as mPTP 0.2.5 writes `<prefix>.txt` (output.c / dp.c).
  const out = 'Command: mptp --ml --multi --tree_file t.nwk --output_file mptp --outgroup D1,D2 --outgroup_crop\n'
      'Number of edges greater than minimum branch length: 9 / 10\n'
      'Null-model score: 12.345678\n'
      'Best score for multi coalescent rate: 20.000000\n'
      'LRT computed p-value: 0.000123\n'
      'LRT: passed\n'
      'Number of delimited species: 3\n'
      '\nSpecies 1:\nA1\nA2\n'
      '\nSpecies 2:\nB1\nB2\nB3\n'
      '\nSpecies 3:\nC1\n';

  test('mPTP output: species, scores and LRT', () {
    final d = parseMptp(out, PtpModel.multi);
    expect(d.species, [
      ['A1', 'A2'],
      ['B1', 'B2', 'B3'],
      ['C1'],
    ]);
    expect(d.nullLogL, closeTo(12.345678, 1e-9));
    expect(d.logL, closeTo(20, 1e-9));
    expect(d.pvalue, closeTo(0.000123, 1e-12));
    expect(d.lrtPassed, isTrue);
    expect(d.singletons, 1);
    expect(d.speciesOf['B2'], 1);
    expect(delimitationTsv(d).split('\n'), ['species\ttip', '1\tA1', '1\tA2', '2\tB1', '2\tB2', '2\tB3', '3\tC1']);
  });

  test('mPTP output: LRT failed lists one species', () {
    const failed = 'Null-model score: 1.0\nBest score for single coalescent rate: 1.1\nLRT computed p-value: 0.9\nLRT: failed\n'
        'Number of delimited species: 2\n\nSpecies 1:\nA\nB\nC\n';
    final d = parseMptp(failed, PtpModel.single, alpha: 0.001);
    expect(d.lrtPassed, isFalse);
    expect(d.species.single, ['A', 'B', 'C']);
    // Collapsed to one species; what the best model had found is kept.
    expect(d.collapsed, isTrue);
    expect(d.bestSpecies, 2);
    expect(d.alpha, 0.001);
    expect(parseMptp(out, PtpModel.multi).collapsed, isFalse);
  });

  test('--minbr_auto answer', () {
    expect(parseMinbr('Command: x\nMinimum branch length (--minbr) should be set to 0.001234\n'), closeTo(0.001234, 1e-12));
    expect(parseMinbr('Minimum branch length (--minbr) should be set to 0\n'), 0);
    expect(parseMinbr('nothing'), isNull);
  });

  test('arguments of the ML run and of --minbr_auto', () {
    expect(
      mptpArgs(tree: 't.nwk', prefix: 'out/mptp', model: PtpModel.multi, outgroup: ['D1', 'D2'], cropOutgroup: true, minbr: 0.0012),
      ['--ml', '--multi', '--tree_file', 't.nwk', '--output_file', 'out/mptp', '--outgroup', 'D1,D2', '--outgroup_crop', '--minbr', '0.0012'],
    );
    expect(mptpArgs(tree: 't', prefix: 'p', model: PtpModel.single), ['--ml', '--single', '--tree_file', 't', '--output_file', 'p']);
    expect(mptpMinbrArgs(tree: 't', fasta: 'm.fasta', prefix: 'minbr'), ['--minbr_auto', 'm.fasta', '--tree_file', 't', '--output_file', 'minbr']);
    // With outgroups: never cropped (mPTP stops when the tree has fewer
    // tips than the FASTA).
    expect(mptpMinbrArgs(tree: 't', fasta: 'm.fasta', prefix: 'minbr', outgroup: ['D1']), isNot(contains('--outgroup_crop')));
    expect(mptpArgs(tree: 't', prefix: 'p', model: PtpModel.multi, pvalue: 0.01), containsAllInOrder(['--pvalue', '0.01']));
  });

  test('tree for mPTP: support labels dropped, polytomies resolved', () {
    // IQ-TREE labels (SH-aLRT/UFBoot) and a polytomy of four tips.
    final tree = parseNewick('(A:0.1,B:0.2,(C:0.01,D:0.02,E:0.03,F:0.04)85.3/97:0.3);');
    final nwk = mptpNewick(tree);
    expect(nwk, isNot(contains('85.3')));
    expect(nwk, isNot(contains('97')));
    final back = parseNewick(nwk);
    // Unrooted: three children at the root; every other node binary.
    expect(back.children.length, 3);
    for (final n in back.nodes) {
      if (!identical(n, back) && !n.isTip) expect(n.children.length, 2);
    }
    expect({for (final t in back.tips) t.name}, {'A', 'B', 'C', 'D', 'E', 'F'});
    expect(back.tips.firstWhere((t) => t.name == 'F').length, closeTo(0.04, 1e-12));
  });

  // As ASAP's CreateSpartFile writes it (asap_common.c), ids from
  // delimitationFasta.
  const asapSpart = 'begin spart;\n'
      'Project_name = input;\n'
      'Date = 2026-11-18T20:00:00;\n'
      'N_spartitions = 2 : input_asap_1 / input_asap_2;\n'
      'N_individuals = 5 /  5;\n'
      'N_subsets = 2 : 1.00e-02,? / 3 : ?,?, ? ;\n'
      '[Generated by ASAP with Distance Jukes-Cantor ]\n'
      '[Asap scores for the N_subset above are:]\n'
      '[1.5 /  3.0 ]\n'
      '[WARNING: The sample names below may have been changed to fit SPART specification (only alphanumeric characters and _ )]\n'
      '[Subset scores are p-values; see Puillandre et al. 2021 for details of the algorithm]\n'
      'Individual_assignment = \n'
      's0001 : 1 / 1\n'
      's0002 : 1 / 1\n'
      's0003 : 2 / 2\n'
      's0004 : 2 / 3\n'
      's0005 : 2 / 3;\n'
      'end;\n'
      'Subset_score_type = p-value / p-value ; \n';

  test('SPART (ASAP): partitions in order, scores, names restored', () {
    final names = {'s0001': 'A_1', 's0002': 'A.2', 's0003': 'B_1', 's0004': 'C_1', 's0005': 'C_2'};
    final parts = parseSpart(asapSpart.replaceAll('\n', '\r\n'), names);
    expect(parts, hasLength(2));
    expect(parts[0].name, 'input_asap_1');
    expect(parts[0].score, '1.5');
    expect(parts[0].species, [
      ['A_1', 'A.2'],
      ['B_1', 'C_1', 'C_2'],
    ]);
    expect(parts[1].score, '3.0');
    expect(parts[1].species, hasLength(3));
  });

  test('SPART (ABGD): N_subsets without p-values, barcode gap scores', () {
    const abgd = 'begin spart;\nProject_name = input;\nDate = x;\nN_spartitions = 2 : input_abgd_init_1 / input_abgd_init_2;\n'
        'N_individuals = 3 /  3;\nN_subsets = 2 / 3;\n[Generated by ABGD with Distance JC69 / MinSlope = 1.500000]\n[Barcode gap distance :]\n'
        '[1.00e-02 / 2.000000e-02]\n[WARNING: x]\nIndividual_assignment = \ns0001 : 1 / 1\ns0002 : 1 / 2\ns0003 : 2 / 3;\nend;\n';
    final parts = parseSpart(abgd);
    expect([for (final p in parts) p.species.length], [2, 3]);
    expect(parts.first.score, '1.00e-02');
    expect(parts.first.species.first, ['s0001', 's0002']);
  });

  test('ABGD priors: log scale from Pmin to Pmax', () {
    final p = abgdPriors(0.001, 0.1, 3);
    expect(p, hasLength(3));
    expect(p[0], closeTo(0.001, 1e-12));
    expect(p[1], closeTo(0.01, 1e-9));
    expect(p[2], closeTo(0.1, 1e-12));
    expect(abgdPriors(0.001, 0.1, 10), hasLength(10));
  });

  test('FASTA for ASAP/ABGD: short ids, upper case, ? as N', () {
    final (fasta, names) = delimitationFasta([('NC_1.1_Fam_Gen_sp', 'acg?-t'), ('X', 'AC GT')]);
    expect(fasta, '>s0001\nACGN-T\n>s0002\nACGT\n');
    expect(names, {'s0001': 'NC_1.1_Fam_Gen_sp', 's0002': 'X'});
  });

  test('ASAP and ABGD arguments', () {
    expect(asapArgs(fasta: 'input.fasta', outDir: 'asap', distance: DelimDistance.k2p), ['-d', '0', '-o', 'asap', 'input.fasta']);
    expect(abgdArgs(fasta: 'input.fasta', outDir: 'abgd'),
        ['-a', '-d', '1', '-p', '0.001', '-P', '0.1', '-n', '10', '-X', '1.5', '-o', 'abgd', 'input.fasta']);
  });

  test('LSD2 arguments: relative dates, outgroup or estimated root', () {
    expect(lsd2Args(tree: 't.nwk', prefix: 'out/lsd2', seqLength: 1500, outgroupFile: 'og.txt'),
        ['-i', 't.nwk', '-s', '1500', '-a', '0', '-z', '1', '-g', 'og.txt', '-G', '-o', 'out/lsd2']);
    expect(lsd2Args(tree: 't', prefix: 'p', seqLength: 10), contains('-r'));
    expect(lsd2OutgroupFile(['D1', 'D2']), '2\nD1\nD2\n');
  });

  test('ultrametric tree from LSD2 .date.nexus', () {
    const nexus = '#NEXUS\nBegin trees;\ntree 1 = [&R] ((A:0.5[&date=1],B:0.5[&date=1])[&date=0.5]:0.5,C:1[&date=1])[&date=0];\nEnd;\n';
    final nwk = ultrametricFromNexus(nexus)!;
    expect(nwk, isNot(contains('[')));
    final t = parseNewick(nwk);
    expect({for (final x in t.tips) x.name}, {'A', 'B', 'C'});
    expect(ultrametricFromNexus('nothing'), isNull);
  });

  test('GMYC JSON', () {
    final d = parseGmyc('{"best_logl": 10.5, "null_logl": 3.2, "pvalue": 0.001, "threshold_species": 2, "lrt_passed": true, "species": [["A","B"],["C"]]}', alpha: 0.01);
    expect(d.bestSpecies, 2);
    expect(d.alpha, 0.01);
    expect(d.species, [
      ['A', 'B'],
      ['C'],
    ]);
    expect(d.lrtPassed, isTrue);
    expect(d.pvalue, closeTo(0.001, 1e-12));
    expect(gmycArgs(tree: 'u.nwk', out: 'g.json'), ['u.nwk', '--pvalue', '0.01', '--out', 'g.json']);
  });
}
