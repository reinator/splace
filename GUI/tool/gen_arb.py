"""Generates lib/l10n/app_{en,pt,es}.arb from one table.

Run: python3 tool/gen_arb.py   (then flutter gen-l10n / flutter run)
All placeholders are Strings; format numbers in Dart before passing them.
Texts shared with the HTML app (docs/js/i18n) are kept identical.
"""
import json, re, pathlib

# ---------------------------------------------------------------------------
# Texts reused verbatim from the HTML app (docs/js/i18n/*.js).
# ---------------------------------------------------------------------------
_ROOT = pathlib.Path(__file__).resolve().parents[2]


def _load_html():
    out = {}
    for f in sorted((_ROOT / "docs" / "js" / "i18n").glob("*.js")):
        t = f.read_text(encoding="utf-8")
        for m in re.finditer(r"\n\s{4}(en|pt|es):\s*\{", t):
            lang, start, depth, i = m.group(1), m.end(), 1, m.end()
            while depth:
                ch = t[i]
                if ch == '"':
                    i += 1
                    while t[i] != '"':
                        i += 2 if t[i] == "\\" else 1
                elif ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                i += 1
            for k, v in re.findall(r'"([^"]+)":\s*"((?:[^"\\]|\\.)*)"', t[start : i - 1]):
                v = json.loads('"' + v + '"')
                v = re.sub(r"<[^>]+>", "", v).replace("&mdash;", "—").replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
                out.setdefault(lang, {})[k] = re.sub(r"\s+", " ", v).strip()
    return out


_H = _load_html()


def h(key):
    return tuple(_H[lang][key] for lang in ("en", "pt", "es"))


