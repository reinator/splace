"""Extracts the SynGenes synonym tables (Rabelo et al. 2024) from the HTML
app (docs/splace.js) into lib/src/core/syngenes_data.dart, so both apps use
the same gene-name standardization."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs" / "splace.js"
OUT = Path(__file__).resolve().parents[1] / "lib" / "src" / "core" / "syngenes_data.dart"


def extract(js: str, name: str) -> dict:
    start = js.index(f"const {name} = {{")
    body_start = js.index("{", start)
    depth = 0
    for i in range(body_start, len(js)):
        if js[i] == "{":
            depth += 1
        elif js[i] == "}":
            depth -= 1
            if depth == 0:
                literal = js[body_start : i + 1]
                break
    literal = re.sub(r",\s*([}\]])", r"\1", literal)
    return json.loads(literal)


def dart_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def dart_map(name: str, table: dict) -> str:
    lines = [f"const Map<String, List<String>> {name} = {{"]
    for key, synonyms in table.items():
        items = ", ".join(dart_str(s) for s in synonyms)
        lines.append(f"  {dart_str(key)}: [{items}],")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    js = SRC.read_text(encoding="utf-8")
    mt = extract(js, "MitochondrialGenes")
    cp = extract(js, "ChloroplastGenes")
    OUT.write_text(
        "// GENERATED by tool/gen_syngenes.py from docs/splace.js. Do not edit.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n\n"
        + dart_map("mitochondrialGenes", mt)
        + "\n\n"
        + dart_map("chloroplastGenes", cp)
        + "\n",
        encoding="utf-8",
    )
    print(f"{len(mt)} mitochondrial and {len(cp)} chloroplast genes -> {OUT}")


if __name__ == "__main__":
    main()
